#!/usr/bin/env bash
set -euo pipefail

# Deterministic regression test for the transport used by bootstrap_cluster.sh
# and smoke_test.sh. A stub grpcurl records every argv and answers with fixed
# responses, so no cluster, Docker, or load is involved. It proves that mTLS
# (the default) presents the operator certificate to coordinators and the
# client certificate to the gateway, that plaintext development identities are
# sent only for explicit development-plaintext in a development KVDB_ENV, and
# that every other configuration fails before any RPC. It also checks that
# generate_tls.sh produces every credential path docker-compose.yml mounts.

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
bootstrap="$repo_root/scripts/bootstrap_cluster.sh"
smoke="$repo_root/scripts/smoke_test.sh"
generate="$repo_root/scripts/generate_tls.sh"

work="${ORBIT_SCRATCH_DIR:-${TMPDIR:-/tmp}}/cluster-transport-test.$$"
mkdir -p "$work/bin"
trap 'rm -rf "$work"' EXIT

export STUB_CALL_LOG="$work/calls.log"
export STUB_VALUE_FILE="$work/value"
export GATEWAY_ADDR="stub-gateway:7000"
export COORDINATOR_ADDRS="stub-coordinator:9001"
export LEADER_DISCOVERY_TIMEOUT_SECONDS=2
export N_NODES=2

cat > "$work/bin/grpcurl" <<'STUB'
#!/usr/bin/env bash
# Stub grpcurl: one log line per call, the argv joined by US (0x1f).
set -euo pipefail
data='{}'
args=("$@")
for ((i=0; i<${#args[@]}; i++)); do
  [[ "${args[$i]}" == "-d" ]] && data="${args[$((i + 1))]}"
done
( IFS=$'\x1f'; printf '%s\n' "${args[*]}" ) >> "$STUB_CALL_LOG"
method="${args[$((${#args[@]} - 1))]}"
case "${method##*/}" in
  GetCoordinatorLeader) echo '{"isLeader": true}' ;;
  RegisterNode|InitShards) echo '{"success": true}' ;;
  Put)
    sed -n 's/.*"value":"\([^"]*\)".*/\1/p' <<< "$data" > "$STUB_VALUE_FILE"
    echo '{"version": "1"}'
    ;;
  Get) echo "{\"kv\": {\"value\": \"$(cat "$STUB_VALUE_FILE")\", \"version\": \"1\"}}" ;;
  *) echo "stub grpcurl: unexpected method $method" >&2; exit 1 ;;
esac
STUB
chmod +x "$work/bin/grpcurl"
export PATH="$work/bin:$PATH"

failures=0
pass() { printf 'PASS: %s\n' "$1"; }
fail() { printf 'FAIL: %s\n' "$1" >&2; failures=$((failures + 1)); }

reset_calls() { : > "$STUB_CALL_LOG"; rm -f "$STUB_VALUE_FILE"; }
call_count() { wc -l < "$STUB_CALL_LOG" | tr -d ' '; }
# Calls (one per line, argv separated by spaces) whose method matches <pattern>.
calls_for() { grep -E "$1\$" "$STUB_CALL_LOG" | tr '\037' ' ' || true; }

# Runs <cmd...> in a clean transport environment plus the given assignments.
# usage: run_with <assignments...> -- <cmd...>
run_with() {
  local -a assignments=()
  while [[ "$1" != "--" ]]; do assignments+=("$1"); shift; done
  shift
  env -u KVDB_GRPC_SECURITY_MODE -u KVDB_ENV -u KVDB_OPERATOR_TLS_DIR \
    -u KVDB_OPERATOR_TLS_TRUST_BUNDLE -u KVDB_OPERATOR_TLS_CERT_CHAIN -u KVDB_OPERATOR_TLS_PRIVATE_KEY \
    -u KVDB_OPERATOR_TLS_SERVER_NAME -u KVDB_CLIENT_TLS_TRUST_BUNDLE -u KVDB_CLIENT_TLS_CERT_CHAIN \
    -u KVDB_CLIENT_TLS_PRIVATE_KEY -u KVDB_CLIENT_TLS_SERVER_NAME -u SMOKE_FIXTURE_FILE \
    ${assignments[@]+"${assignments[@]}"} "$@" > "$work/out.log" 2>&1
}

expect_ok() { # label assignments... -- cmd...
  local label="$1"; shift
  reset_calls
  if run_with "$@"; then pass "$label"; else fail "$label"; cat "$work/out.log" >&2; fi
}

# A refused configuration must fail without reaching grpcurl.
expect_refused() { # label message-pattern assignments... -- cmd...
  local label="$1" pattern="$2"; shift 2
  reset_calls
  if run_with "$@"; then
    fail "$label (unexpectedly succeeded)"
  elif [[ "$(call_count)" != "0" ]]; then
    fail "$label (issued $(call_count) RPC(s) before refusing)"
  elif ! grep -Eq "$pattern" "$work/out.log"; then
    fail "$label (missing diagnostic /$pattern/)"; cat "$work/out.log" >&2
  else
    pass "$label"
  fi
}

# usage: assert_calls <label> <method pattern> <required flag pair...> -- <forbidden text...>
assert_calls() {
  local label="$1" pattern="$2" calls item ok=true
  shift 2
  calls="$(calls_for "$pattern")"
  if [[ -z "$calls" ]]; then
    fail "$label (no $pattern call recorded)"
    return
  fi
  while [[ $# -gt 0 && "$1" != "--" ]]; do
    if grep -vqF -- "$1" <<< "$calls"; then ok=false; echo "    missing '$1'" >&2; fi
    shift
  done
  [[ $# -gt 0 ]] && shift
  for item in "$@"; do
    if grep -qF -- "$item" <<< "$calls"; then ok=false; echo "    unexpected '$item'" >&2; fi
  done
  if $ok; then pass "$label"; else fail "$label"; printf '%s\n' "$calls" >&2; fi
}

# Credentials: generated by the documented tool, so the layout it writes is the
# layout the helpers read.
creds="$work/creds"
workload="$creds/workload"
operator="$creds/operator"
if KVDB_TLS_DIR="$workload" KVDB_OPERATOR_TLS_DIR="$operator" "$generate" > "$work/generate.log" 2>&1; then
  pass "generate_tls.sh issues workload and operator credentials"
else
  fail "generate_tls.sh failed"; cat "$work/generate.log" >&2
  exit 1
fi

# 1. Every credential file docker-compose.yml mounts exists in the generated set.
missing=0
while read -r secret; do
  [[ -f "$workload/${secret#/run/secrets/kvdb/}" ]] || { echo "    missing $secret" >&2; missing=$((missing + 1)); }
done < <(grep -Eo '/run/secrets/kvdb/[A-Za-z0-9./_-]+' "$repo_root/docker-compose.yml" | sort -u)
(( missing == 0 )) && pass "generated workload set covers every Compose credential path" || fail "Compose credential paths missing"
[[ ! -e "$workload/operator" && ! -e "$workload/client" ]] \
  && pass "operator and client keys are not in the Compose-mounted directory" \
  || fail "operator or client credentials leaked into KVDB_TLS_DIR"

san() { openssl x509 -in "$1" -noout -ext subjectAltName 2>/dev/null | tr -d ' \n'; }
[[ "$(san "$operator/operator/tls.crt")" == *"URI:spiffe://kvdb/admin/operator" ]] \
  && pass "operator certificate carries an admin identity" || fail "operator identity: $(san "$operator/operator/tls.crt")"
[[ "$(san "$operator/client/tls.crt")" == *"URI:spiffe://kvdb/client/smoke/smoke-test" ]] \
  && pass "client certificate carries a client identity" || fail "client identity: $(san "$operator/client/tls.crt")"
[[ "$(san "$workload/coordinator-1/tls.crt")" == *"DNS:localhost"* && "$(san "$workload/gateway-server/tls.crt")" == *"DNS:localhost"* ]] \
  && pass "loopback-published server certificates verify as localhost" || fail "server certificates lack localhost"
if openssl verify -CAfile "$operator/internal-ca-bundle.pem" "$operator/operator/tls.crt" "$workload/gateway-server/tls.crt" >/dev/null 2>&1 \
  && openssl verify -CAfile "$workload/gateway-client-ca-bundle.pem" "$operator/client/tls.crt" >/dev/null 2>&1 \
  && ! openssl verify -CAfile "$workload/gateway-client-ca-bundle.pem" "$operator/operator/tls.crt" >/dev/null 2>&1; then
  pass "operator chains to the internal CA, client to the gateway client CA only"
else
  fail "credential issuers"
fi
before="$(find "$creds" -type f | wc -l | tr -d ' ')"
if KVDB_TLS_DIR="$workload" KVDB_OPERATOR_TLS_DIR="$work/other-operator" "$generate" > "$work/out.log" 2>&1; then
  fail "generate_tls.sh overwrote a non-empty directory"
else
  pass "generate_tls.sh refuses a non-empty directory"
fi
if KVDB_TLS_DIR="$work/nested" KVDB_OPERATOR_TLS_DIR="$work/nested/operator" "$generate" > "$work/out.log" 2>&1; then
  fail "generate_tls.sh accepted operator credentials inside KVDB_TLS_DIR"
else
  pass "generate_tls.sh refuses operator credentials inside KVDB_TLS_DIR"
fi
[[ "$(find "$creds" -type f | wc -l | tr -d ' ')" == "$before" ]] && pass "refused generation left credentials untouched" || fail "credentials changed"

operator_flags=(-cacert "$operator/internal-ca-bundle.pem" -cert "$operator/operator/tls.crt" -key "$operator/operator/tls.key")
client_flags=(-cacert "$operator/gateway-ca-bundle.pem" -cert "$operator/client/tls.crt" -key "$operator/client/tls.key")
plaintext_markers=(-plaintext x-kvdb-development-identity)

# 2. mTLS is the default and the explicit mode: scoped certificates, never plaintext.
for mode_assignment in "KVDB_GRPC_SECURITY_MODE=mtls" "KVDB_GRPC_SECURITY_MODE= MTLS " "KVDB_ENV=docker"; do
  expect_ok "bootstrap succeeds with [$mode_assignment]" "$mode_assignment" "KVDB_OPERATOR_TLS_DIR=$operator" -- "$bootstrap"
  assert_calls "[$mode_assignment] coordinator calls present the operator certificate" \
    'Coordinator/(GetCoordinatorLeader|RegisterNode|InitShards)' \
    "-cacert $operator/internal-ca-bundle.pem" "-cert $operator/operator/tls.crt" "-key $operator/operator/tls.key" \
    -- "${plaintext_markers[@]}" "$operator/client/"
done

expect_ok "mTLS smoke test round-trips through the gateway" "KVDB_OPERATOR_TLS_DIR=$operator" -- "$smoke"
assert_calls "gateway calls present the client certificate" 'KvGateway/(Put|Get)' \
  "-cacert $operator/gateway-ca-bundle.pem" "-cert $operator/client/tls.crt" "-key $operator/client/tls.key" \
  -- "${plaintext_markers[@]}" "$operator/operator/"
assert_calls "smoke bootstrap still uses the operator certificate" 'Coordinator/InitShards' \
  "-cert $operator/operator/tls.crt" -- "${plaintext_markers[@]}" "$operator/client/"
grep -q 'Smoke test passed' "$work/out.log" && pass "mTLS smoke test verified the gateway value" || fail "smoke test did not verify the value"

# 3. Explicit files and verified server names override the directory defaults.
alt="$work/alt"
mkdir -p "$alt"
cp "$operator/operator/tls.crt" "$alt/op.crt"; cp "$operator/operator/tls.key" "$alt/op.key"
expect_ok "explicit operator credential files are honored" \
  "KVDB_OPERATOR_TLS_TRUST_BUNDLE=$operator/internal-ca-bundle.pem" \
  "KVDB_OPERATOR_TLS_CERT_CHAIN=$alt/op.crt" "KVDB_OPERATOR_TLS_PRIVATE_KEY=$alt/op.key" \
  "KVDB_OPERATOR_TLS_SERVER_NAME=coordinator1" -- "$bootstrap"
assert_calls "explicit operator files and server name reach grpcurl" 'Coordinator/InitShards' \
  "-cert $alt/op.crt" "-key $alt/op.key" "-authority coordinator1" -- "${plaintext_markers[@]}"
expect_ok "client server name override" "KVDB_OPERATOR_TLS_DIR=$operator" "KVDB_CLIENT_TLS_SERVER_NAME=gateway" -- "$smoke"
assert_calls "client server name reaches gateway calls only" 'KvGateway/(Put|Get)' "-authority gateway" -- -plaintext
assert_calls "client server name is not used for coordinators" 'Coordinator/InitShards' "-cert" -- "-authority"

# 4. Plaintext only for explicit development-plaintext in a development deployment.
for deployment in local dev development test " Test "; do
  expect_ok "development-plaintext with KVDB_ENV='$deployment'" \
    "KVDB_GRPC_SECURITY_MODE=development-plaintext" "KVDB_ENV=$deployment" -- "$smoke"
  assert_calls "KVDB_ENV='$deployment' coordinator calls use the development admin identity" 'Coordinator/InitShards' \
    "-plaintext" "x-kvdb-development-identity: admin/bootstrap-local" -- -cacert -cert -key
  assert_calls "KVDB_ENV='$deployment' gateway calls use the development client identity" 'KvGateway/(Put|Get)' \
    "-plaintext" "x-kvdb-development-identity: client/local/smoke-test" -- -cacert -cert -key
done

# 5. Fail closed: refused before any RPC, with a diagnostic.
expect_refused "default mode without credentials refuses bootstrap" 'mTLS operator credentials are not configured' -- "$bootstrap"
expect_refused "explicit mtls without credentials refuses the smoke test" 'mTLS client credentials are not configured' \
  "KVDB_GRPC_SECURITY_MODE=mtls" -- "$smoke"
for mode in seed verify; do
  expect_refused "smoke $mode refuses without client credentials" 'mTLS client credentials are not configured' \
    "SMOKE_FIXTURE_FILE=$work/fixture-$mode.tsv" -- "$smoke" "$mode"
done
expect_refused "missing operator key file is refused" 'KVDB_OPERATOR_TLS_PRIVATE_KEY must name a readable file' \
  "KVDB_OPERATOR_TLS_DIR=$operator" "KVDB_OPERATOR_TLS_PRIVATE_KEY=$work/absent.key" -- "$bootstrap"
expect_refused "missing client certificate is refused" 'KVDB_CLIENT_TLS_CERT_CHAIN must name a readable file' \
  "KVDB_OPERATOR_TLS_DIR=$operator" "KVDB_CLIENT_TLS_CERT_CHAIN=$work/absent.crt" -- "$smoke"
expect_refused "a directory is not a credential file" 'KVDB_OPERATOR_TLS_TRUST_BUNDLE must name a readable file' \
  "KVDB_OPERATOR_TLS_DIR=$operator" "KVDB_OPERATOR_TLS_TRUST_BUNDLE=$operator" -- "$bootstrap"
for deployment in "" docker prod production staging; do
  expect_refused "development-plaintext with KVDB_ENV='$deployment' is refused" 'requires KVDB_ENV' \
    "KVDB_GRPC_SECURITY_MODE=development-plaintext" "KVDB_ENV=$deployment" "KVDB_OPERATOR_TLS_DIR=$operator" -- "$bootstrap"
done
for mode in plaintext tls insecure development "development plaintext"; do
  expect_refused "unknown mode '$mode' is refused" 'must be mtls or development-plaintext' \
    "KVDB_GRPC_SECURITY_MODE=$mode" "KVDB_ENV=local" "KVDB_OPERATOR_TLS_DIR=$operator" -- "$smoke"
done

if (( failures > 0 )); then
  echo "${failures} cluster transport check(s) failed" >&2
  exit 1
fi
echo "All cluster transport checks passed"
